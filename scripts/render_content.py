#!/usr/bin/env python3
"""Render replaceable public prose to static GitHub Pages HTML.

Only content/site.json and content/*.md are editorial source files.  All other
HTML is a generated display; manuscript PDF/TeX files are untouched.
"""
from pathlib import Path
import json, re, html, sys, unicodedata
import mistune

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / 'docs'
CONTENT = ROOT / 'content'
DATA = json.loads((CONTENT/'site.json').read_text(encoding='utf-8'))
MANIFEST = json.loads((DOC/'data/manifest.json').read_text(encoding='utf-8'))
PAPER_RELEASE = MANIFEST['papersRelease'].replace('_', '.')
DAG_RELEASE = MANIFEST['dagRelease'].replace('_','.')
AUDIT_RELEASE = MANIFEST['auditRelease'].replace('_','.')
E = lambda x: html.escape(str(x), quote=True)
MARKDOWN = mistune.create_markdown(escape=True, plugins=['table','strikethrough','url'])

# Use an existing generated homepage as the common visual shell. The HTML is
# committed, so markdown changes need no import at site runtime.
OLD = (DOC/'index.html').read_text(encoding='utf-8')
HEAD = re.sub(r'^(?:<!-- GENERATED by scripts/render_content.py; edit files in content/ -->\s*)+', '', OLD.split('<main id="main">', 1)[0])
FOOT = OLD.split('</main>', 1)[1]
SVG_MATCH = re.search(r'(<div class="hero-art">.*?</div>)', OLD, flags=re.S)
# Save the original SVG in a separate static component for subsequent reruns.
ART_FILE = ROOT / 'content' / 'hero-art.html'
if not ART_FILE.exists():
    if not SVG_MATCH:
        raise RuntimeError('Original homepage hero illustration missing')
    ART_FILE.write_text(SVG_MATCH.group(1), encoding='utf-8')
ART = ART_FILE.read_text(encoding='utf-8')

NAV = [
    ('Overview','index.html','home'),
    ('Framework','framework.html','framework'),
    ('Observables','observables.html','observables'),
    ('Papers','papers.html','papers'),
    ('Verification','verification.html','verification'),
]

def navbar(active):
    links = []
    for name,href,key in NAV:
        cls = ' class="active" aria-current="page"' if active==key else ''
        links.append(f'<a href="{href}"{cls}>{E(name)}</a>')
    return '<nav class="main-nav" aria-label="Primary">'+''.join(links)+'</nav>'

def make_footer():
    return f'''<footer class="site-footer"><div class="container footer-grid"><div>
<a href="index.html" class="footer-brand">BORN–HOPF <span>GEOMETRY</span></a>
<p>A geometry-first research programme working from mathematical structures to specific questions about measurable physics.</p>
<p class="foot-muted">Author: {E(DATA['author'])} · Source snapshot: {E(MANIFEST['snapshotDate'])}</p></div><div>
<h3>Understand</h3><a href="index.html">Start here</a><a href="framework.html">The framework explained</a><a href="observables.html">What must be explained?</a><a href="glossary.html">Key terms</a></div><div>
<h3>Research archive</h3><a href="papers.html">31 manuscripts</a><a href="geometry.html">Geometry diagrams</a><a href="verification.html">Verification records</a><a href="downloads.html">Downloads & provenance</a><a href="about.html">About & citation</a></div></div>
<div class="container footer-bottom"><span>Paper corpus: {E(PAPER_RELEASE)} · DAG atlas: {E(DAG_RELEASE)} · Audits: {E(AUDIT_RELEASE)}</span><span>Mathematical construction, physical realization, and observation are distinct claims.</span></div></footer>'''

def slug(text):
    text = html.unescape(re.sub(r'<[^>]+>', '', text)).split(':', 1)[0]
    text = unicodedata.normalize('NFKD', text)
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')

def render_markdown(name):
    raw = (CONTENT/name).read_text(encoding='utf-8')
    output = MARKDOWN(raw)
    toc = []
    used = set()
    def assign(m):
        level=int(m.group(1)); content=m.group(2)
        s=slug(content)
        candidate=s; index=2
        while s in used:
            s=f'{candidate}-{index}';index+=1
        used.add(s)
        if level==2: toc.append((content,s))
        return f'<h{level} id="{E(s)}">{content}</h{level}>'
    output = re.sub(r'<h([123])>(.*?)</h\1>', assign, output, flags=re.S)
    return output, toc

def shell(title, main, active, description):
    head = re.sub(r'<title>.*?</title>', '<title>'+E(title)+' · Born–Hopf Geometry</title>', HEAD)
    head = re.sub(r'(<meta name="description" content=")[^"]*', r'\g<1>'+E(description), head)
    head = re.sub(r'(<meta property="og:title" content=")[^"]*', r'\g<1>'+E(title+' — Born–Hopf Geometry'), head)
    head = re.sub(r'(<meta property="og:description" content=")[^"]*', r'\g<1>'+E(description), head)
    head = re.sub(r'<nav class="main-nav".*?</nav>', navbar(active), head, flags=re.S)
    head = re.sub(r'<body data-page="[^"]*"', '<body data-page="'+E(active)+'"', head)
    foot = re.sub(r'<footer class="site-footer">.*?</footer>', make_footer(), FOOT, flags=re.S)
    return '<!-- GENERATED by scripts/render_content.py; edit files in content/ -->\n'+head+'<main id="main">'+main+'</main>'+foot

def anchor_button(text,href,variant):
    return f'<a class="btn btn-{variant}" href="{E(href)}">{E(text)} <span aria-hidden="true">→</span></a>'

def card(item):
    return f'''<a href="{E(item['href'])}" class="concept-card"><span class="concept-index">{E(item['index'])}</span>
<h3>{E(item['title'])}</h3><p>{E(item['text'])}</p><span class="concept-arrow" aria-hidden="true">Explore →</span></a>'''

